# PROGRAM LOOPING ANGKA 1 - 100
# Bahasa : Python
# Fungsi : Menampilkan angka dari 1 sampai 100
# =========================================================

# Menampilkan judul program
print("=" * 60)
print("              PROGRAM LOOPING ANGKA")
print("=" * 60)

# Penjelasan program
print("\nProgram ini akan menampilkan angka dari 1 sampai 100")
print("menggunakan perulangan (loop) pada Python.\n")

print("-" * 60)

# Perulangan angka 1 sampai 100
for angka in range(1, 101):

    # Menampilkan angka
    print(f"Angka ke-{angka}")

print("-" * 60)

# Pesan akhir program
print("Semua angka dari 1 sampai 100 berhasil ditampilkan.")
print("=" * 60)
